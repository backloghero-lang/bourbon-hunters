import fs from "node:fs";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),"..");
const indexSource=fs.readFileSync(path.join(root,"index.html"),"utf8");
const versionMatch=indexSource.match(/const APP_VERSION\s*=\s*"([0-9]+)"/);
if(!versionMatch) throw new Error("APP_VERSION is missing from index.html");

const core=[
  "./",
  "./index.html",
  "./spirit-taxonomy.js",
  "./manifest.json",
  "./design/figma-assets/home-pack-v2/app-background-v3.jpg",
  "./design/figma-assets/home-pack-v2/home-header-v3.jpg",
  "./design/figma-assets/home-pack-v2/card-background-v1.jpg",
  "./icons/icon-192.png",
  "./icons/icon-512.png"
];

for(const asset of core){
  if(asset==="./") continue;
  const diskPath=path.join(root,asset.replace(/^\.\//,""));
  if(!fs.existsSync(diskPath)) throw new Error("Missing core PWA asset: "+asset);
}

const output=`/* Generated by scripts/generate-sw-manifest.mjs. */
self.BH_SW_MANIFEST=Object.freeze({
  version:"${versionMatch[1]}",
  core:Object.freeze(${JSON.stringify(core,null,4)})
});
`;
const outputPath=path.join(root,"sw-assets.generated.js");
if(process.argv.includes("--check")){
  if(!fs.existsSync(outputPath)||fs.readFileSync(outputPath,"utf8")!==output) throw new Error("sw-assets.generated.js is out of date");
  console.log("Service worker manifest is current: v"+versionMatch[1]+", "+core.length+" core assets");
}else{
  fs.writeFileSync(outputPath,output,"utf8");
  console.log("Generated sw-assets.generated.js for v"+versionMatch[1]);
}
